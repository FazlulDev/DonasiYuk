export function getLang() {
  const stored = localStorage.getItem('sy_lang');
  return stored === 'en' ? 'en' : 'id';
}

export function setLang(nextLang) {
  const lang = nextLang === 'en' ? 'en' : 'id';
  localStorage.setItem('sy_lang', lang);
  document.documentElement.lang = lang;
  return lang;
}

export function t(key) {
  const lang = getLang();
  return DICT[lang]?.[key] || DICT.id[key] || key;
}
